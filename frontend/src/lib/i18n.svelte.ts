export const dicts: Record<LangId, Dict> = { pt, en, es, zh }

// Reactive module state: reading currentLang inside a component render or a
// $derived registers it as a dependency, so swapping the language updates
// every t() in the UI without a full remount.
let currentLang = $state<LangId>('pt')

export function setLang(lang: LangId): void {
  currentLang = lang
}

export function langId(v: string): LangId {
  const id = v.toLowerCase() as LangId
  return id in dicts ? id : 'pt'
}

// t formats {placeholders} with the given values; a missing key falls back to
// the pt entry and then to the key itself.
export function t(key: string, vars: Record<string, string | number> = {}): string {
  let s = dicts[currentLang][key] ?? dicts.pt[key] ?? key
  for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v))
  return s
}